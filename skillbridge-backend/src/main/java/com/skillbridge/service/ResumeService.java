package com.skillbridge.service;

import com.skillbridge.config.SkillBridgeProperties;

import org.apache.pdfbox.Loader;
import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.text.PDFTextStripper;
import org.springframework.core.io.FileSystemResource;
import org.springframework.core.io.Resource;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;
import org.springframework.web.multipart.MultipartFile;
import org.springframework.web.server.ResponseStatusException;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.UUID;

// Stores résumé PDFs on disk and extracts their text with PDFBox
@Service
public class ResumeService {

    private static final long MAX_BYTES = 5L * 1024 * 1024;
    private static final int MAX_TEXT_LENGTH = 100_000;
    private static final byte[] PDF_MAGIC = {'%', 'P', 'D', 'F', '-'};

    private final Path resumeDir;

    public ResumeService(SkillBridgeProperties properties) {
        this.resumeDir = Paths.get(properties.upload().dir(), "resumes")
                .toAbsolutePath()
                .normalize();
    }

    public record StoredResume(String originalFileName, String storagePath, String text) {
    }

    public StoredResume store(Long userId, MultipartFile file) {

        if (file == null || file.isEmpty()) {
            throw new ResponseStatusException(
                    HttpStatus.BAD_REQUEST, "Choose a PDF résumé to upload");
        }

        if (file.getSize() > MAX_BYTES) {
            throw new ResponseStatusException(
                    HttpStatus.CONTENT_TOO_LARGE,
                    "File is too large. Maximum size is 5 MB");
        }

        byte[] bytes;

        try {
            bytes = file.getBytes();
        } catch (IOException e) {
            throw new ResponseStatusException(
                    HttpStatus.BAD_REQUEST, "Could not read the uploaded file");
        }

        if (!isPdf(bytes)) {
            throw new ResponseStatusException(
                    HttpStatus.BAD_REQUEST, "Only PDF résumés are supported");
        }

        String text = extractText(bytes);

        Path target = resumeDir.resolve(userId + "-" + UUID.randomUUID() + ".pdf");

        try {
            Files.createDirectories(resumeDir);
            Files.write(target, bytes);
        } catch (IOException e) {
            throw new ResponseStatusException(
                    HttpStatus.INTERNAL_SERVER_ERROR, "Could not save the résumé");
        }

        return new StoredResume(
                cleanFileName(file.getOriginalFilename()),
                target.getFileName().toString(),
                text);
    }

    public String extractText(byte[] pdfBytes) {

        try (PDDocument document = Loader.loadPDF(pdfBytes)) {

            if (document.isEncrypted()) {
                throw new ResponseStatusException(
                        HttpStatus.BAD_REQUEST,
                        "Password-protected PDFs are not supported");
            }

            String text = new PDFTextStripper().getText(document);
            text = text.replace(' ', ' ').strip();

            return text.length() > MAX_TEXT_LENGTH
                    ? text.substring(0, MAX_TEXT_LENGTH)
                    : text;

        } catch (IOException e) {
            throw new ResponseStatusException(
                    HttpStatus.BAD_REQUEST, "The PDF could not be read");
        }
    }

    public Resource load(String storagePath) {

        Path file = resolve(storagePath);

        if (file == null || !Files.isReadable(file)) {
            throw new ResponseStatusException(
                    HttpStatus.NOT_FOUND, "Résumé file not found");
        }

        return new FileSystemResource(file);
    }

    public void delete(String storagePath) {

        Path file = resolve(storagePath);

        if (file == null) {
            return;
        }

        try {
            Files.deleteIfExists(file);
        } catch (IOException ignored) {
            // A leftover file is harmless; the profile no longer points to it
        }
    }

    // Stored names are generated by us, but never allow escaping the directory
    private Path resolve(String storagePath) {

        if (storagePath == null) {
            return null;
        }

        Path file = resumeDir.resolve(storagePath).normalize();

        return file.startsWith(resumeDir) ? file : null;
    }

    private static boolean isPdf(byte[] bytes) {

        if (bytes.length < PDF_MAGIC.length) {
            return false;
        }

        for (int i = 0; i < PDF_MAGIC.length; i++) {
            if (bytes[i] != PDF_MAGIC[i]) {
                return false;
            }
        }

        return true;
    }

    private static String cleanFileName(String name) {

        if (name == null || name.isBlank()) {
            return "resume.pdf";
        }

        String base = Paths.get(name).getFileName().toString()
                .replaceAll("[^A-Za-z0-9._ -]", "_");

        return base.length() > 120 ? base.substring(0, 120) : base;
    }
}
